            "DRIVE_BUNDLE_ZIP = os.path.join(DRIVE_MYDRIVE, 'trading_saas_bundle.zip')\n",
            "DRIVE_FOLDER = os.path.join(DRIVE_MYDRIVE, 'trading-saas')\n",
            "\n",
            "if os.path.exists(DRIVE_BUNDLE_ZIP):\n",
