            "    print(\"  -> Descomprimiendo en /content/trading-saas...\")\n",
            "    os.makedirs(TARGET_DIR, exist_ok=True)\n",
            "    with zipfile.ZipFile(DRIVE_BUNDLE_ZIP, 'r') as zf:\n",
            "        zf.extractall(TARGET_DIR)\n",
            "elif os.path.exists(DRIVE_FOLDER):\n",
            "    print(f\"  -> Encontrada carpeta de proyecto en Drive: {DRIVE_FOLDER}\")\n",
